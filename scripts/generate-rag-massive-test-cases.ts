async function main(): Promise<void> {
  const cases: MassiveTestCase[] = [];
  let index = 1;
  for (const spec of specs) {
    for (const query of spec.queries) {
      cases.push({
        id: `M${String(index).padStart(3, "0")}`,
        category: spec.category,
        query,
        expectedBehavior: spec.behavior,
        forbiddenBehavior: spec.forbidden,
        expectedRetrievalThemes: spec.themes,
        expectedConfidenceRange: { min: spec.min, max: spec.max },
        notes: spec.notes,
      });
      index += 1;
    }
  }
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, `${JSON.stringify(cases, null, 2)}\n`, "utf8");
  console.log(`Generated ${cases.length} massive RAG test cases at ${outputPath}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
